using System.Text;
using Microsoft.CodeAnalysis;
using Square.Compiler.Directives;
using Square.Compiler.LanguageServices;
using Square.Compiler.Parser;
using Square.Compiler.Template;
using Square.Compiler.Template.Compatibility;

namespace Square.Compiler.Emit
{
    internal sealed class ComponentEmitter
    {
        private readonly TemplateDocument _doc;
        private readonly string _namespace;
        private readonly StringBuilder _sb = new StringBuilder();
        private readonly List<RefInfo> _refs = new List<RefInfo>();
        private readonly DirectiveCatalog _catalog;
        private readonly TemplateCatalog _templateCatalog;
        private readonly Compilation _compilation;
        private readonly Dictionary<string, TemplateComponentDescriptor> _variableComponents =
            new Dictionary<string, TemplateComponentDescriptor>(StringComparer.Ordinal);
        private readonly IReadOnlyDictionary<int, TemplateElementResolution> _resolutions;
        private readonly List<TemplateGeneratedSourceMapping> _sourceMappings = new List<TemplateGeneratedSourceMapping>();
        private DirectiveEmitPipeline _pipeline;
        private int _vforIndex;
        private int _vifIndex;
        private int _varCounter;
        private int _slotCounter;
        private bool _hasObjectBindings;
        /// <summary>当前发射位置是否处于 HTML pre/textarea 祖先内；只有这里保留纯空白文本。</summary>
        private bool _preserveWhitespace;

        public ComponentEmitter(
            SqxDocument doc,
            string namespaceName,
            DirectiveCatalog catalog,
            Compilation compilation,
            TemplateCatalog templateCatalog,
            TemplateResolutionContext resolutionContext,
            IReadOnlyDictionary<int, TemplateElementResolution> resolutions)
            : this(TemplateDocument.From(doc), namespaceName, catalog, compilation, templateCatalog, resolutionContext, resolutions)
        {
        }

        public ComponentEmitter(
            TemplateDocument doc,
            string namespaceName,
            DirectiveCatalog catalog,
            Compilation compilation,
            TemplateCatalog templateCatalog,
            TemplateResolutionContext resolutionContext,
            IReadOnlyDictionary<int, TemplateElementResolution> resolutions)
        {
            _doc = doc ?? throw new ArgumentNullException(nameof(doc));
            _catalog = catalog ?? throw new ArgumentNullException(nameof(catalog));
            _templateCatalog = templateCatalog ?? throw new ArgumentNullException(nameof(templateCatalog));
            _resolutions = resolutions ?? throw new ArgumentNullException(nameof(resolutions));
            _compilation = compilation;
            _namespace = !string.IsNullOrWhiteSpace(doc.Namespace)
                ? doc.Namespace
                : string.IsNullOrWhiteSpace(namespaceName) ? "Square.Sample" : namespaceName;
        }

        public string Emit()
        {
            ResetState();
            var roots = GetTemplateRoots();
            CollectRefs(roots);
            _hasObjectBindings = HasObjectBindings(roots);
            var (scriptUsings, scriptBody) = GetScriptParts();
            var isGeneratedComponent = !HasCustomPaintOverride();

            _sb.AppendLine("// <auto-generated/>");
            _sb.AppendLine("#nullable enable");
            _sb.AppendLine();
            foreach (var defaultUsing in TemplateScriptDefaults.UsingDirectives)
                _sb.Append("using ").Append(defaultUsing).AppendLine(";");
            foreach (var usingDirective in scriptUsings.Where(usingDirective =>
                         !TemplateScriptDefaults.UsingDirectives.Any(defaultUsing =>
                             usingDirective.Equals("using " + defaultUsing + ";", StringComparison.Ordinal))))
                _sb.AppendLine(usingDirective);
            _sb.AppendLine();
            _sb.AppendLine("namespace " + _namespace + ";");
            _sb.AppendLine();
            _sb.AppendLine(_doc.Access + " partial class " + _doc.Name + " : global::Square.UI.UIElement");
            _sb.AppendLine("#if DEBUG");
            _sb.AppendLine("    , Square.Hosting.ISquareHotReloadComponent");
            _sb.AppendLine("#endif");
            _sb.AppendLine("{");

            EmitFields();
            _sb.AppendLine("    protected override bool IsGeneratedComponent => " +
                (isGeneratedComponent ? "true" : "false") + ";");
            _sb.AppendLine();
            _sb.AppendLine("#if DEBUG");
            _sb.AppendLine("    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]");
            _sb.AppendLine("#endif");
            _sb.AppendLine("    public override void BuildElementTree()");
            _sb.AppendLine("    {");
            _sb.AppendLine("        if (_visualTreeBuilt) return;");
            _sb.AppendLine("        _visualTreeBuilt = true;");
            EmitNodes(roots, "        ", "this", Array.Empty<string>());
            _sb.AppendLine("        ApplyComponentStyles(this);");
            _sb.AppendLine("#if DEBUG");
            _sb.AppendLine("        _hotReloadVersion = CurrentHotReloadVersion();");
            _sb.AppendLine("#endif");
            _sb.AppendLine("    }");

            EmitScript(scriptBody);
            EmitStyleSupport();
            EmitHotReloadSupport();
            _sb.AppendLine("}");
            return _sb.ToString();
        }

        private List<SqxNode> GetTemplateRoots()
        {
            if (_doc.Ir == null || _doc.Syntax?.Template == null) return _doc.Roots;
            return TemplateIrCompatibilityAdapter.ToSqxNodes(
                _doc.Ir,
                _doc.Syntax.SourceText,
                _doc.Syntax.Dialect,
                _doc.Syntax.Template.ContentRange.Offset);
        }

        internal IReadOnlyList<TemplateGeneratedSourceMapping> SourceMappings => _sourceMappings;

        private void ResetState()
        {
            _varCounter = 0;
            _slotCounter = 0;
            _hasObjectBindings = false;
            _preserveWhitespace = false;
            _vforIndex = 0;
            _vifIndex = 0;
            _refs.Clear();
            _variableComponents.Clear();
            _sourceMappings.Clear();
            _sb.Clear();
            _pipeline = new DirectiveEmitPipeline(
                _sb,
                _catalog,
                EmitNodes,
                EmitFactoryBody,
                EmitAttribute,
                NextVariable);
            _pipeline.ResetFieldIndexes();
        }

        private void CollectRefs(List<SqxNode> nodes)
        {
            foreach (var node in nodes)
            {
                if (node is SqxElement element)
                {
                    var refAttr = FindAttr(element, "ref");
                    if (refAttr != null && !string.IsNullOrWhiteSpace(refAttr.RawValue) &&
                        !_refs.Exists(item => item.Name == refAttr.RawValue))
                    {
                        _refs.Add(new RefInfo(refAttr.RawValue, MapTagName(ResolveDescriptor(element))));
                    }
                    CollectRefs(element.Children);
                }
                else if (node is TemplateForDirective forDirective)
                    CollectRefs(forDirective.Children);
                else if (node is TemplateIfChainDirective ifChain)
                    foreach (var branch in ifChain.Branches)
                        CollectRefs(branch.Children);
            }
        }

        private void EmitFields()
        {
            _sb.AppendLine("    private bool _visualTreeBuilt;");
            foreach (var item in _refs)
                _sb.AppendLine("    internal " + item.TypeName + " " + item.Name + " = null!;");
            _sb.AppendLine("#if DEBUG");
            _sb.AppendLine("    private long _hotReloadVersion;");
            _sb.AppendLine("#endif");
            _sb.AppendLine();
        }

        private void EmitNodes(List<SqxNode> nodes, string indent, string parentName, IReadOnlyList<string> localNames)
        {
            foreach (var node in nodes)
            {
                if (IsWrapperExpression(node)) continue;

                if (node is SqxText text)
                {
                    var htmlContext = IsHtmlParent(parentName);
                    // 纯缩进空白只保留在 pre/textarea 祖先内；其余纯空白忽略。
                    if (!_preserveWhitespace && string.IsNullOrWhiteSpace(text.Text)) continue;
                    var textName = EmitText(text.Text, indent, htmlContext);
                    _sb.AppendLine(indent + parentName +
                        (htmlContext ? ".ChildNodes.Add(" : ".Children.Add(") + textName + ");");
                }
                else if (node is SqxExpression expression)
                {
                    var htmlContext = IsHtmlParent(parentName);
                    var textName = EmitExpressionText(expression.Expression, indent, localNames, parentName, htmlContext);
                    _sb.AppendLine(indent + parentName +
                        (htmlContext ? ".ChildNodes.Add(" : ".Children.Add(") + textName + ");");
                }
                else if (node is SqxElement element)
                {
                    if (IsTemplateFragment(element))
                    {
                        EmitNodes(element.Children, indent, parentName, localNames);
                        continue;
                    }

                    // Catalog-driven structural directives (Show/For/Switch/Slot/Router/…)。
                    // Resolved HTML/SVG elements never enter Square's directive pipeline.
                    if (element.Resolution?.Component?.IsHtmlHost != true &&
                        element.Resolution?.Component?.Kind != TemplateElementKind.Svg &&
                        _catalog.IsDirective(element.TagName))
                    {
                        _pipeline.TryEmit(element, indent, parentName, localNames);
                        continue;
                    }

                    var elementName = EmitControl(element, indent, localNames, parentName);
                    _sb.AppendLine(indent + parentName + ".Children.Add(" + elementName + ");");
                    if (ResolveDescriptor(element).RequiresBuildAfterAttach)
                        _sb.AppendLine(indent + elementName + ".BuildElementTree();");
                }
                else if (node is TemplateForDirective forDirective)
                {
                    EmitVFor(forDirective, indent, parentName, localNames);
                }
                else if (node is TemplateIfChainDirective ifChain)
                {
                    EmitVIfChain(ifChain, indent, parentName, localNames);
                }
            }
        }

        private string EmitControl(SqxElement element, string indent, IReadOnlyList<string> localNames, string parentName = null)
        {
            var refAttr = FindAttr(element, "ref");
            var isRef = refAttr != null && !string.IsNullOrWhiteSpace(refAttr.RawValue);
            var variableName = isRef ? refAttr.RawValue : NextVariable();
            var descriptor = ResolveDescriptor(element);
            // 113 个 HTML 标签各映射唯一具体类型，与 Square 控件一样无参构造。
            var tagName = "global::" + descriptor.TypeName + "()";
            var usesSlots = descriptor.IsSlotHost;
            _variableComponents[variableName] = descriptor;

            if (isRef)
                _sb.AppendLine(indent + variableName + " = new " + tagName + ";");
            else
                _sb.AppendLine(indent + "var " + variableName + " = new " + tagName + ";");
            var tagStart = GetLineColumn(element.TagNamePosition);
            var tagEnd = GetLineColumn(element.TagNamePosition + Math.Max(1, element.TagNameLength));
            _sb.AppendLine(indent + variableName + ".SetDebugInfo(ElementDebugInfo.Create(" +
                StableSourceId(_doc.SourcePath) + ", " + tagStart.Line + ", " + tagStart.Column + ", " +
                tagEnd.Line + ", " + tagEnd.Column +
                ", \"" + Escape(string.IsNullOrEmpty(element.OriginalTagName) ? element.TagName : element.OriginalTagName) +
                "\", \"" + Escape(_doc.Name) + "\", sourcePath: \"" +
                Escape(_doc.SourcePath) + "\"));");
            if (descriptor.Kind == TemplateElementKind.Extension)
                _sb.AppendLine(indent + variableName + ".MarkTemplateExport(\"" + Escape(descriptor.NamespaceUri) +
                    "\", \"" + Escape(descriptor.LocalName) + "\");");
            var customDefinition = descriptor.CustomElementName != null
                ? descriptor : _templateCatalog.FindCustomDefinitionFor(descriptor);
            if (customDefinition != null)
            {
                var observed = string.Join(", ", customDefinition.ObservedAttributes.Select(name => "\"" + Escape(name) + "\""));
                _sb.AppendLine(indent + "global::Square.Html.HtmlCustomElementRegistry.InitializeGenerated(" +
                    variableName + ", \"" + Escape(customDefinition.CustomElementName) + "\", " +
                    (customDefinition.CustomExtendsTag == null ? "null" : "\"" + Escape(customDefinition.CustomExtendsTag) + "\"") +
                    ", new string[] { " + observed + " });");
            }

            // Initialize properties before events, then let v-model write back before user handlers.
            // Property hooks may emit events, so model listeners must not exist during initialization.
            foreach (var attribute in element.Attributes.Where(attribute => !IsEventAttribute(attribute)))
                EmitAttribute(variableName, attribute, indent, localNames);
            foreach (var attribute in element.Attributes.Where(attribute => attribute.IsModelEvent))
                EmitAttribute(variableName, attribute, indent, localNames);
            foreach (var attribute in element.Attributes.Where(attribute => IsEventAttribute(attribute) && !attribute.IsModelEvent))
                EmitAttribute(variableName, attribute, indent, localNames);

            if (usesSlots)
            {
                EmitComponentSlots(element, variableName, indent, localNames);
            }
            else
            {
                var parentPreserveWhitespace = _preserveWhitespace;
                _preserveWhitespace = parentPreserveWhitespace ||
                    (descriptor.IsHtmlHost && IsPreformattedTag(descriptor.TagName));
                if (!EmitTextContent(element, variableName, indent, localNames))
                    EmitNodes(element.Children, indent, variableName, localNames);
                _preserveWhitespace = parentPreserveWhitespace;
            }

            return variableName;
        }

        private static bool IsEventAttribute(SqxAttribute attribute) =>
            attribute.IsModelEvent || attribute.IsDynamicEvent ||
            attribute.Name == "__sqv_on_object" ||
            attribute.IsExpression && attribute.Name.StartsWith("on", StringComparison.OrdinalIgnoreCase);

        private void EmitAttribute(string variableName, SqxAttribute attribute, string indent, IReadOnlyList<string> localNames)
        {
            var isHtml = IsHtmlVariable(variableName);
            if (attribute.Name == "ref" || attribute.Name == "slot" && !isHtml) return;

            if (attribute.IsDynamicProperty)
            {
                var start = MappingStart();
                _sb.AppendLine(indent + variableName + ".RegisterGeneratedResource(SqvObjectBinding.BindProperty(" + variableName + ", " + attribute.ArgumentExpression + ", " + attribute.RawValue + "));");
                MapSource(TemplateGeneratedSourceKind.PropertyBinding, start, AttributeSourceRange(attribute));
                return;
            }

            if (attribute.IsDynamicEvent)
            {
                var start = MappingStart();
                _sb.AppendLine(indent + variableName + ".RegisterGeneratedResource(SqvObjectBinding.BindEvent(" + variableName + ", " + attribute.ArgumentExpression + ", " + attribute.RawValue + "));");
                MapSource(TemplateGeneratedSourceKind.EventHandler, start, AttributeSourceRange(attribute));
                return;
            }

            if (attribute.Name == "__sqv_bind_object")
            {
                var start = MappingStart();
                _sb.AppendLine(indent + variableName + ".RegisterGeneratedResource(SqvObjectBinding.BindProperties(" + variableName + ", " + attribute.RawValue + "));");
                MapSource(TemplateGeneratedSourceKind.PropertyBinding, start, AttributeSourceRange(attribute));
                return;
            }

            if (attribute.Name == "__sqv_on_object")
            {
                var start = MappingStart();
                _sb.AppendLine(indent + variableName + ".RegisterGeneratedResource(SqvObjectBinding.BindEvents(" + variableName + ", " + attribute.RawValue + "));");
                MapSource(TemplateGeneratedSourceKind.EventHandler, start, AttributeSourceRange(attribute));
                return;
            }

            if (attribute.Name == "class" && !attribute.IsExpression)
            {
                foreach (var className in Split(attribute.RawValue, ' '))
                    if (!string.IsNullOrWhiteSpace(className))
                        _sb.AppendLine(indent + variableName + ".ClassList.Add(\"" + Escape(className) + "\");");
                return;
            }

            if (attribute.Name == "style" && !attribute.IsExpression)
            {
                _sb.AppendLine(indent + variableName + ".Style.CssText = \"" + Escape(attribute.RawValue) + "\";");
                return;
            }

            if (attribute.IsExpression)
            {
                if (attribute.Name.StartsWith("on", StringComparison.OrdinalIgnoreCase))
                {
                    var eventName = attribute.Name.Substring(2).ToLowerInvariant();
                    var componentEvent = FindComponentEvent(variableName, eventName);
                    var eventArgument = componentEvent == null
                        ? "\"" + eventName + "\""
                        : MapTagName(_variableComponents[variableName]) + "." + componentEvent.MemberName;
                    var handlerExpression = attribute.IsModelEvent
                        ? BuildModelWriteBack(attribute, _variableComponents[variableName])
                        : attribute.RawValue;
                    var start = MappingStart();
                    EmitSourceMappedLine(indent, attribute.Line,
                        variableName + ".RegisterGeneratedResource(" + variableName + ".Listen(" +
                        eventArgument + ", " + handlerExpression + "));");
                    MapSource(TemplateGeneratedSourceKind.EventHandler, start, AttributeSourceRange(attribute));
                }
                else
                {
                    // HTML 动态属性绑定小写 attribute 名；Square 控件继续走别名映射。
                    var propertyName = isHtml
                        ? attribute.Name.ToLowerInvariant()
                        : MapPropName(_variableComponents[variableName], attribute.Name);
                    var start = MappingStart();
                    if (IsLocalExpression(attribute.RawValue, localNames))
                        EmitSourceMappedLine(indent, attribute.Line,
                            variableName + ".SetProperty(\"" + propertyName + "\", " + attribute.RawValue + ");");
                    else
                        EmitSourceMappedLine(indent, attribute.Line,
                            variableName + ".BindProperty(\"" + propertyName + "\", " + attribute.RawValue + ");");
                    MapSource(TemplateGeneratedSourceKind.PropertyBinding, start, AttributeSourceRange(attribute));
                }
                return;
            }

            var propName = MapPropName(_variableComponents.TryGetValue(variableName, out var elementType) ? elementType : null, attribute.Name);
            var rawValue = attribute.RawValue ?? "";
            if (isHtml && !attribute.Name.Equals("id", StringComparison.OrdinalIgnoreCase))
            {
                // HTML 静态属性直接落 attribute：不做 bool/int 强转；布尔属性写 "false" 表示缺席；
                // 空值/裸写保留为空字符串 attribute（存在即真）。id 继续走既有 Id 属性通道。
                var attributeName = attribute.Name.ToLowerInvariant();
                if (Square.Html.HtmlTagCatalog.BooleanAttributes.Contains(attributeName) &&
                    rawValue.Equals("false", StringComparison.OrdinalIgnoreCase))
                    return;
                _sb.AppendLine(indent + variableName + ".SetAttribute(\"" + Escape(attributeName) + "\", \"" + Escape(rawValue) + "\");");
                return;
            }
            if (attribute.Name.Equals("disabled", StringComparison.OrdinalIgnoreCase) && string.IsNullOrEmpty(rawValue))
                _sb.AppendLine(indent + variableName + ".SetProperty(\"" + propName + "\", true);");
            else if (bool.TryParse(rawValue, out var boolValue))
                _sb.AppendLine(indent + variableName + ".SetProperty(\"" + propName + "\", " + boolValue.ToString().ToLowerInvariant() + ");");
            else if (int.TryParse(rawValue, out var intValue))
                _sb.AppendLine(indent + variableName + ".SetProperty(\"" + propName + "\", " + intValue + ");");
            else
                _sb.AppendLine(indent + variableName + ".SetProperty(\"" + propName + "\", \"" + Escape(rawValue) + "\");");
        }

        private bool EmitTextContent(SqxElement element, string variableName, string indent, IReadOnlyList<string> localNames)
        {
            if (!ResolveDescriptor(element).IsTextContentElement) return false;
            if (FindAttr(element, "text") != null) return true;

            var content = element.Children.Where(node => !IsWrapperExpression(node)).ToList();
            if (content.Count == 0) return true;
            if (content.All(node => node is SqxText))
            {
                var value = string.Concat(content.Cast<SqxText>().Select(node => node.Text));
                _sb.AppendLine(indent + variableName + ".SetProperty(\"TextContent\", \"" + Escape(NormalizeText(value)) + "\");");
                return true;
            }
            if (content.Count == 1 && content[0] is SqxExpression expression)
            {
                if (IsLocalExpression(expression.Expression, localNames))
                    _sb.AppendLine(indent + variableName + ".SetProperty(\"TextContent\", $\"{(" + expression.Expression + ")}\");");
                else
                    _sb.AppendLine(indent + variableName + ".BindProperty(\"TextContent\", " + expression.Expression + ");");
                return true;
            }
            if (content.All(node => node is SqxText or SqxExpression))
            {
                var interpolated = string.Concat(content.Select(node => node switch
                {
                    SqxText text => EscapeInterpolatedText(text.Text),
                    SqxExpression expression => "{(" + expression.Expression + ")}",
                    _ => string.Empty
                }));
                var sources = content.OfType<SqxExpression>()
                    .Where(expression => !IsLocalExpression(expression.Expression, localNames))
                    .Select(expression => expression.Expression.Trim())
                    .Where(IsSimpleMemberExpression)
                    .Distinct(StringComparer.Ordinal)
                    .ToList();
                var sourceArgs = sources.Count == 0 ? "" : ", " + string.Join(", ", sources);
                _sb.AppendLine(indent + variableName + ".BindProperty(\"TextContent\", () => $\"" +
                    interpolated + "\"" + sourceArgs + ");");
                return true;
            }
            return false;
        }

        private void EmitComponentSlots(SqxElement element, string variableName, string indent, IReadOnlyList<string> localNames)
        {
            var groups = new List<SlotGroup>();
            foreach (var child in element.Children)
            {
                if (IsWrapperExpression(child)) continue;
                var slotName = "";
                var slotNameIsExpression = false;
                TemplateSlotScope slotScope = null;
                var slotNodes = new List<SqxNode> { child };
                if (child is SqxElement childElement)
                {
                    var slotAttribute = FindAttr(childElement, "slot");
                    slotName = slotAttribute?.RawValue ?? "";
                    slotNameIsExpression = slotAttribute?.IsExpression == true;
                    slotScope = childElement.SlotScope;
                    if (IsTemplateFragment(childElement))
                        slotNodes = childElement.Children;
                }

                var groupIndex = groups.FindIndex(group =>
                    group.NameIsExpression == slotNameIsExpression &&
                    string.Equals(group.Name, slotName, StringComparison.Ordinal) &&
                    ReferenceEquals(group.Scope, slotScope));
                if (groupIndex < 0)
                {
                    groups.Add(new SlotGroup(slotName, slotNameIsExpression, slotScope, new List<SqxNode>(slotNodes)));
                }
                else
                {
                    groups[groupIndex].Nodes.AddRange(slotNodes);
                }
            }

            foreach (var group in groups)
            {
                var parentParameter = "__slotParent" + _slotCounter++;
                var name = group.NameIsExpression ? group.Name : "\"" + Escape(group.Name) + "\"";
                var parameters = group.Scope == null
                    ? parentParameter
                    : "(" + parentParameter + ", __slotProps)";
                var slotOrigin = group.Scope != null
                    ? new SquareSourceRange(group.Scope.Position, 1)
                    : group.Nodes.Count > 0
                        ? new SquareSourceRange(group.Nodes[0].Position, Math.Max(1, group.Name.Length))
                        : new SquareSourceRange(0, 0);
                var mappingStart = MappingStart();
                _sb.AppendLine(indent + variableName + ".Slots.Set(" + name + ", " + parameters + " =>");
                _sb.AppendLine(indent + "{");
                var scopeLocals = localNames;
                if (!string.IsNullOrWhiteSpace(group.Scope?.WholePropsName))
                {
                    _sb.AppendLine(indent + "    var " + group.Scope.WholePropsName + " = __slotProps;");
                    scopeLocals = AddLocals(scopeLocals, group.Scope.WholePropsName);
                }
                else if (group.Scope != null)
                {
                    foreach (var binding in group.Scope.Properties)
                    {
                        var bindingStart = MappingStart();
                        _sb.AppendLine(indent + "    var " + binding.LocalName + " = __slotProps.Get<" + binding.TypeName + ">(\"" + Escape(binding.PropertyName) + "\");");
                        scopeLocals = AddLocals(scopeLocals, binding.LocalName);
                        MapSource(TemplateGeneratedSourceKind.SlotBinding, bindingStart,
                            binding.Length > 0
                                ? new SquareSourceRange(binding.Position, binding.Length)
                                : slotOrigin);
                    }
                }
                EmitNodes(group.Nodes, indent + "    ", parentParameter, scopeLocals);
                _sb.AppendLine(indent + "});");
                MapSource(TemplateGeneratedSourceKind.SlotBinding, mappingStart, slotOrigin);
            }
        }

        private void EmitVFor(TemplateForDirective directive, string indent, string parentName, IReadOnlyList<string> localNames)
        {
            var field = "_vfor" + _vforIndex++;
            var item = directive.ItemName;
            var hasIndex = !string.IsNullOrEmpty(directive.IndexName);
            var lambda = hasIndex ? "(" + item + ", " + directive.IndexName + ")" : item;
            var keySelector = string.IsNullOrWhiteSpace(directive.KeyExpression)
                ? ""
                : lambda + " => " + directive.KeyExpression + ", ";
            _sb.AppendLine(indent + "var " + field + " = ForNode.Create(" + directive.SourceExpression + ", " + keySelector + lambda + " =>");
            _sb.AppendLine(indent + "{");
            EmitFactoryBody(directive.Children, indent + "    ",
                AddLocals(localNames, item, directive.IndexName));
            _sb.AppendLine(indent + "});");
            _sb.AppendLine(indent + parentName + ".RegisterGeneratedResource(" + field + ");");
            _sb.AppendLine(indent + field + ".AttachTo(" + parentName + ");");
        }

        private void EmitVIfChain(TemplateIfChainDirective chain, string indent, string parentName, IReadOnlyList<string> localNames)
        {
            string accumulated = null;
            foreach (var branch in chain.Branches)
            {
                var field = "_vif" + _vifIndex++;
                string condition;
                if (branch.IsElse)
                    condition = accumulated == null ? "true" : "!(" + accumulated + ")";
                else if (accumulated == null)
                    condition = branch.Condition ?? "false";
                else
                    condition = "!(" + accumulated + ") && (" + (branch.Condition ?? "false") + ")";

                accumulated = accumulated == null
                    ? "(" + (branch.Condition ?? "false") + ")"
                    : accumulated + " || (" + (branch.Condition ?? "false") + ")";

                _sb.AppendLine(indent + "var " + field + " = new ShowNode(" + condition + ", () =>");
                _sb.AppendLine(indent + "{");
                EmitFactoryBody(branch.Children, indent + "    ", localNames);
                _sb.AppendLine(indent + "});");
                _sb.AppendLine(indent + parentName + ".RegisterGeneratedResource(" + field + ");");
                _sb.AppendLine(indent + field + ".AttachTo(" + parentName + ");");
            }
        }

        private void EmitFactoryBody(List<SqxNode> nodes, string indent, IReadOnlyList<string> localNames)
        {
            var content = nodes.Where(node => !IsWrapperExpression(node)).ToList();
            if (content.Count == 0)
            {
                _sb.AppendLine(indent + "return null;");
                return;
            }

            if (content.Count == 1)
            {
                var rootName = EmitFactoryRoot(content[0], indent, localNames);
                _sb.AppendLine(indent + "ApplyComponentStyles(" + rootName + ");");
                _sb.AppendLine(indent + "return " + rootName + ";");
                return;
            }

            var fragmentName = NextVariable();
            _sb.AppendLine(indent + "var " + fragmentName + " = new global::Square.Controls.View();");
            EmitNodes(content, indent, fragmentName, localNames);
            _sb.AppendLine(indent + "ApplyComponentStyles(" + fragmentName + ");");
            _sb.AppendLine(indent + "return " + fragmentName + ";");
        }

        private string EmitFactoryRoot(SqxNode node, string indent, IReadOnlyList<string> localNames)
        {
            if (node is SqxElement element)
            {
                if (element.Resolution?.Component?.IsHtmlHost == true ||
                    element.Resolution?.Component?.Kind == TemplateElementKind.Svg ||
                    !_catalog.IsDirective(element.TagName))
                    return EmitControl(element, indent, localNames);
                var wrapper = NextVariable();
                _sb.AppendLine(indent + "var " + wrapper + " = new global::Square.Controls.View();");
                EmitNodes(new List<SqxNode> { node }, indent, wrapper, localNames);
                return wrapper;
            }
            if (node is SqxText text)
                return EmitText(text.Text, indent);
            if (node is SqxExpression expression)
                return EmitExpressionText(expression.Expression, indent, localNames, null!, htmlContext: false);

            // Vue 专属指令作为工厂根：用 View 包装，使其可作为 Element 返回。
            if (node is TemplateForDirective or TemplateIfChainDirective)
            {
                var wrapper = NextVariable();
                _sb.AppendLine(indent + "var " + wrapper + " = new global::Square.Controls.View();");
                EmitNodes(new List<SqxNode> { node }, indent, wrapper, localNames);
                return wrapper;
            }

            var fallback = NextVariable();
            _sb.AppendLine(indent + "var " + fallback + " = new global::Square.Controls.View();");
            return fallback;
        }

        private string EmitText(string value, string indent, bool htmlContext = false)
        {
            var variableName = NextVariable();
            // HTML 父节点下混合文本是真正的 DOM Text 节点（保留原文空白）；Square 父节点维持 Trim 后的控件文本。
            var textTypeName = htmlContext ? "global::Square.UI.Text" : "global::Square.Controls.Text";
            _sb.AppendLine(indent + "var " + variableName + " = new " + textTypeName + "(\"" + Escape(htmlContext ? value : NormalizeText(value)) + "\");");
            return variableName;
        }

        private string EmitExpressionText(string expression, string indent, IReadOnlyList<string> localNames, string parentName, bool htmlContext)
        {
            var variableName = NextVariable();
            if (htmlContext)
            {
                // 已解析 HTML 父节点下动态文本是 DOM Text：静态局部表达式一次赋值，其余经 HtmlTextBinding 订阅。
                _sb.AppendLine(indent + "var " + variableName + " = new global::Square.UI.Text();");
                if (IsLocalExpression(expression, localNames))
                    _sb.AppendLine(indent + variableName + ".Data = $\"{(" + expression + ")}\";");
                else
                    _sb.AppendLine(indent + "global::Square.Html.HtmlTextBinding.Bind(" + parentName + ", " + variableName + ", " + expression + ");");
                return variableName;
            }
            _sb.AppendLine(indent + "var " + variableName + " = new global::Square.Controls.Text();");
            if (IsLocalExpression(expression, localNames))
                _sb.AppendLine(indent + variableName + ".SetProperty(\"TextContent\", $\"{(" + expression + ")}\");");
            else
                _sb.AppendLine(indent + variableName + ".BindProperty(\"TextContent\", " + expression + ");");
            return variableName;
        }

        private void EmitScript(string scriptCode)
        {
            if (string.IsNullOrWhiteSpace(scriptCode)) return;
            _sb.AppendLine();
            _sb.AppendLine("    #region Script");
            if (!string.IsNullOrWhiteSpace(_doc.SourcePath))
                _sb.AppendLine("#line 1 \"" + Escape(_doc.SourcePath) + "\"");
            var mappingStart = MappingStart();
            foreach (var line in scriptCode.Split('\n'))
                _sb.AppendLine("    " + line.TrimEnd('\r'));
            MapSource(
                TemplateGeneratedSourceKind.Script,
                mappingStart,
                _doc.Syntax?.Script?.ContentRange ?? new SquareSourceRange(0, 0));
            if (!string.IsNullOrWhiteSpace(_doc.SourcePath))
                _sb.AppendLine("#line default");
            _sb.AppendLine("    #endregion");
        }

        private bool HasCustomPaintOverride()
        {
            var members = _doc.Syntax?.Script?.CSharp.Members;
            if (members?.OfType<Microsoft.CodeAnalysis.CSharp.Syntax.MethodDeclarationSyntax>()
                    .Any(method => method.Identifier.ValueText == "Paint") == true)
                return true;

            return _compilation?.GetTypeByMetadataName(_namespace + "." + _doc.Name)?
                .GetMembers("Paint")
                .OfType<IMethodSymbol>()
                .Any(method => method.MethodKind == MethodKind.Ordinary) == true;
        }

        private (IReadOnlyList<string> Usings, string Body) GetScriptParts()
        {
            var script = _doc.Syntax?.Script;
            if (script == null) return (Array.Empty<string>(), string.Empty);

            var usings = script.CSharp.Usings
                .Select(directive => directive.WithoutTrivia().NormalizeWhitespace().ToFullString())
                .ToArray();
            var bodyText = script.ContentText.Trim();
            if (bodyText.Length == 0) return (usings, string.Empty);
            var trimStart = script.ContentText.IndexOf(bodyText, StringComparison.Ordinal);
            if (trimStart < 0) return (usings, bodyText);

            var lines = bodyText.Split('\n');
            foreach (var directive in script.CSharp.Usings)
            {
                var start = Math.Max(0, Math.Min(directive.Span.Start - trimStart, bodyText.Length));
                var end = Math.Max(start, Math.Min(directive.Span.End - trimStart, bodyText.Length));
                var startLine = GetLineIndex(bodyText, start);
                var endLine = GetLineIndex(bodyText, Math.Max(start, end - 1));
                for (var line = startLine; line <= endLine && line < lines.Length; line++) lines[line] = string.Empty;
            }
            return (usings, string.Join("\n", lines));
        }

        private static int GetLineIndex(string text, int position)
        {
            var line = 0;
            for (var index = 0; index < position && index < text.Length; index++)
                if (text[index] == '\n') line++;
            return line;
        }

