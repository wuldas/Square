        private static string Escape(string value) =>
            value.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\r", "\\r").Replace("\n", "\\n");

        private static int StableSourceId(string value)
        {
            unchecked
            {
                var hash = 17;
                foreach (var character in value ?? "") hash = hash * 31 + character;
                return hash;
            }
        }

        private void EmitSourceMappedLine(string indent, int line, string code)
        {
            if (!string.IsNullOrWhiteSpace(_doc.SourcePath) && line > 0)
                _sb.AppendLine("#line " + line + " \"" + Escape(_doc.SourcePath) + "\"");
            _sb.AppendLine(indent + code);
            if (!string.IsNullOrWhiteSpace(_doc.SourcePath) && line > 0)
                _sb.AppendLine("#line default");
        }

